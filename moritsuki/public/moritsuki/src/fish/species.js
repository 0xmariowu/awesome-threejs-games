// 体長(cm) → 重さ(kg)
export function weightOf(sp, cm) {
  if (sp.model === 'octopus') return 0.4 + ((cm - 40) / 50) * 2.6;
  if (sp.model === 'lobster') return 0.25 + ((cm - 20) / 14) * 0.55;
  return sp.wc * Math.pow(cm / 30, 3);
}
export function valueOf(sp, cm, headshot) {
  const w = weightOf(sp, cm);
  return Math.round((w * sp.price * (headshot ? 1.2 : 1)) / 10) * 10;
}

