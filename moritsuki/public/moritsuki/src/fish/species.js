// 魚種データ: 形・模様・行動・値段・料理
// 形（shape）は全長 = 1 の側面図で書く。X は吻端からの距離、Y は上。
//   top / bot / wid: 背の輪郭・腹の輪郭・体の半幅の制御点 [X, 値]（体は X = 0..bl）
//   eye: [X, Y, 半径]、mouth: 口の高さ・切れ込みの長さ・傾き、op: [鰓蓋の縁の X, 中ほどの張り出し]
//   dorsal / anal: 鰭の列 {x0, x1, spines(トゲの数), notch(膜の切れ込み), h(高さの制御点), rake(鰭条の後傾)}
//   caudal: 尾鰭 {type, len, h}、pect / pelv: 胸鰭 / 腹鰭
//   scales: [体の長さ方向の鱗の数, 周方向の数, 凹凸の強さ]
// 模様 pattern(P) の P = {X, Y, u(体の長さの割合), ny(-1 腹 .. 1 背), side, eye(眼からの距離／眼の半径), op(鰓蓋の縁からの距離), lat(側線からの高さ), head}
import { makeNoise2D } from '../core/noise.js';

const N = makeNoise2D(314);
const N2 = makeNoise2D(2718);
const hex = (h) => { const v = parseInt(h.slice(1), 16); return [(v >> 16) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255]; };
const mix = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
const mul = (a, k) => [a[0] * k, a[1] * k, a[2] * k];
const ss = (a, b, x) => { const t = Math.max(0, Math.min(1, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
const fbm = (x, y) => N(x, y) * 0.6 + N(x * 2.1, y * 2.1) * 0.3 + N2(x * 4.3, y * 4.3) * 0.1;
const sil = (c, s) => [c[0], c[1], c[2], s];

// 背→腹のグラデーション（ny: 1 背、-1 腹）
function countershade(top, side, belly, ny) {
  return ny > 0 ? mix(side, top, ss(0.0, 0.85, ny)) : mix(side, belly, ss(0.0, -0.75, ny));
}
// 鰭の基本：付け根→縁でわずかに色を変え、縁は薄く明るい
const finBase = (a, b, t, edge = 0.25) => mix(mix(hex(a), hex(b), t), hex(b), ss(0.85, 1, t) * edge);

